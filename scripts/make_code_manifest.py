"""Write deploy/CODE_MANIFEST.txt: SHA-256 of every CODE file the Windows update script installs.

The update script (deploy/update_windows.ps1) refuses to run unless every listed file in the
downloaded package matches, so a partial or corrupted download can never be half-installed.
Hashes are computed with CRLF normalized to LF (a git checkout on Windows may convert line
endings). The manifest also lists every previously published config/default.toml hash, so the
update script can tell an untouched default.toml from one the user edited by hand.

    python scripts/make_code_manifest.py          # write the manifest
    python scripts/make_code_manifest.py --check  # exit 1 if the manifest is out of date
"""
from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "deploy" / "CODE_MANIFEST.txt"
# Must match $CodeDirs / $CodeFiles in deploy/update_windows.ps1
CODE_DIRS = ["cryptolab", "deploy", "docs", "tests", "scripts"]
CODE_FILES = ["requirements.txt", "requirements-llm.txt", "pyproject.toml", "README.md", "Dockerfile",
              "docker-compose.yml", "config/default.toml"]


def norm_hash(data: bytes) -> str:
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def code_files() -> list[Path]:
    out = []
    for d in CODE_DIRS:
        for p in sorted((ROOT / d).rglob("*")):
            if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc" and p != MANIFEST:
                out.append(p)
    out += [ROOT / f for f in CODE_FILES if (ROOT / f).exists()]
    return out


def known_default_toml_hashes() -> list[str]:
    hashes = set()
    try:
        commits = subprocess.run(["git", "log", "--format=%H", "--", "config/default.toml"], cwd=ROOT,
                                 capture_output=True, text=True, check=True).stdout.split()
        for c in commits:
            blob = subprocess.run(["git", "show", f"{c}:config/default.toml"], cwd=ROOT, capture_output=True,
                                  check=True).stdout
            hashes.add(norm_hash(blob))
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass
    hashes.add(norm_hash((ROOT / "config/default.toml").read_bytes()))
    return sorted(hashes)


def build() -> str:
    lines = ["# CryptoLab code manifest: sha256 (CRLF normalized to LF) + path. Generated by "
             "scripts/make_code_manifest.py -- do not edit by hand."]
    lines += [f"# known-default-toml {h}" for h in known_default_toml_hashes()]
    for p in code_files():
        data = p.read_bytes()
        try:
            data.decode("utf-8")
        except UnicodeDecodeError:
            raise SystemExit(f"not UTF-8 text (the update script hashes text files only): {p}")
        if b"\x00" in data:
            raise SystemExit(f"binary file in a code folder: {p}")
        lines.append(f"{norm_hash(data)}  {p.relative_to(ROOT).as_posix()}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        ok = MANIFEST.exists() and MANIFEST.read_text() == text
        print("manifest up to date" if ok else "manifest OUT OF DATE: run python scripts/make_code_manifest.py")
        raise SystemExit(0 if ok else 1)
    MANIFEST.write_text(text)
    print(f"wrote {MANIFEST.relative_to(ROOT)}: {text.count(chr(10)) - 1} lines")
